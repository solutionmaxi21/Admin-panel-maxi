async function handleAddToCart(client, userId, data) {
  /**
   * Expected data: { productId, quantity, idempotencyKey }
   */
  const { productId, quantity } = data;
  
  if (!productId || !quantity) {
    throw new Error('Missing required fields: productId, quantity');
  }
  
  // For offline sync, cart operations are typically local-only
  // We just acknowledge receipt of the mutation
  // The actual cart is managed client-side in IndexedDB
  
  console.log(`📦 ADD_TO_CART: product ${productId} x${quantity} for user ${userId}`);
  
  return {
    success: true,
    message: 'Item added to cart (synced)',
    productId,
    quantity
  };
}

async function handleRemoveFromCart(client, userId, data) {
  /**
   * Expected data: { productId, idempotencyKey }
   */
  const { productId } = data;
  
  if (!productId) {
    throw new Error('Missing required field: productId');
  }
  
  console.log(`🗑️ REMOVE_FROM_CART: product ${productId} for user ${userId}`);
  
  return {
    success: true,
    message: 'Item removed from cart (synced)',
    productId
  };
}

async function handleUpdateQuantity(client, userId, data) {
  /**
   * Expected data: { productId, quantity, idempotencyKey }
   */
  const { productId, quantity } = data;
  
  if (!productId || quantity === undefined) {
    throw new Error('Missing required fields: productId, quantity');
  }
  
  if (quantity <= 0) {
    throw new Error('Quantity must be greater than 0');
  }
  
  console.log(`📊 UPDATE_QUANTITY: product ${productId} to quantity ${quantity} for user ${userId}`);
  
  return {
    success: true,
    message: 'Quantity updated (synced)',
    productId,
    quantity
  };
}

async function handleAddToWishlist(client, userId, data) {
  /**
   * Expected data: { productId, idempotencyKey }
   */
  const { productId } = data;
  
  if (!productId) {
    throw new Error('Missing required field: productId');
  }
  
  // Check if product exists
  const productResult = await client.query(
    'SELECT id FROM products WHERE id = $1',
    [productId]
  );
  
  if (productResult.rows.length === 0) {
    throw new Error(`Product ${productId} not found`);
  }
  
  // Add to favorites (or update if exists)
  const result = await client.query(
    `INSERT INTO favorites (user_id, product_id)
     VALUES ($1, $2)
     ON CONFLICT (user_id, product_id) 
     DO NOTHING
     RETURNING id`,
    [userId, productId]
  );
  
  console.log(`❤️ ADD_TO_WISHLIST: product ${productId} for user ${userId}`);
  
  return {
    success: true,
    message: 'Item added to wishlist (synced)',
    productId,
    created: result.rows.length > 0
  };
}

async function handleRemoveFromWishlist(client, userId, data) {
  /**
   * Expected data: { productId, idempotencyKey }
   */
  const { productId } = data;
  
  if (!productId) {
    throw new Error('Missing required field: productId');
  }
  
  // Remove from favorites
  const result = await client.query(
    'DELETE FROM favorites WHERE user_id = $1 AND product_id = $2',
    [userId, productId]
  );
  
  console.log(`💔 REMOVE_FROM_WISHLIST: product ${productId} for user ${userId}`);
  
  return {
    success: true,
    message: 'Item removed from wishlist (synced)',
    productId,
    deleted: result.rowCount > 0
  };
}

